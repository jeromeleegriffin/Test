import assert from 'node:assert/strict';
const source=fs.readFileSync('main-v41.mjs','utf8').replace('import { DurableObject } from "cloudflare:workers";', 'class DurableObject {constructor(ctx,env){this.ctx=ctx;this.env=env;}}');
