const api=async(path,body,token)=>{
 const r=await room.fetch(new Request('https://test/'+path,{method:body===undefined?'GET':'POST',headers:{'Content-Type':'application/json',...(token?{Authorization:'Bearer '+token}:{})},...(body===undefined?{}:{body:JSON.stringify(body)})}));
 return {status:r.status,body:await r.json()};
};
const host=(await api('create',{playerId:'host-test-id',displayName:'Host'})).body;
const a=(await api('join',{playerId:'guest-test-a',displayName:'Guest A',preferredSeat:1})).body;
const b=(await api('join',{playerId:'guest-test-b',displayName:'Guest B',preferredSeat:2})).body;
assert.ok(host.token&&a.token&&b.token);
const before=(await api('snapshot',undefined,a.token)).body;
